const express = require('express');
const path = require('path');
const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());
app.use(express.static(path.join(__dirname, './')));

// --- TELEGRAM CONFIGURATION ---
const TELEGRAM_TOKEN = process.env.TELEGRAM_TOKEN;
const TELEGRAM_CHAT_ID = process.env.TELEGRAM_CHAT_ID;

async function sendTelegramMessage(message) {
    if (!TELEGRAM_TOKEN || !TELEGRAM_CHAT_ID) {
        console.log("Telegram credentials missing. Skipping notification.");
        return;
    }
    try {
        const url = `https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage`;
        await fetch(url, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                chat_id: TELEGRAM_CHAT_ID,
                text: message,
                parse_mode: 'HTML'
            })
        });
        console.log("Telegram alert sent!");
    } catch (error) {
        console.error("Telegram error:", error);
    }
}

// --- DATABASE (Temporary Memory) ---
let serverBalances = { demo: 50000, real: 110 };

// --- API ENDPOINTS ---

// 1. Get Balances
app.get('/api/get-balance', (req, res) => {
    res.json({ success: true, demoBalance: serverBalances.demo, realBalance: serverBalances.real });
});

// 2. Update Balance
app.post('/api/update-balance', (req, res) => {
    const { accountType, amount, tradeData } = req.body;
    
    if (accountType === 'demo' || accountType === 'real') {
        serverBalances[accountType] += amount;
        
        if (tradeData) {
            let action = tradeData.direction === 'BUY' ? '🟢 BUY' : '🔴 SELL';
            let msg = `<b>New Trade Executed</b>\n\n` +
                      `Pair: ${tradeData.pair}\n` +
                      `Action: ${action}\n` +
                      `Amount: $${tradeData.amount}\n` +
                      `Account: ${accountType.toUpperCase()}\n` +
                      `Expiry: ${tradeData.expiry}s`;
            sendTelegramMessage(msg);
        }
        
        res.json({ success: true, newBalance: serverBalances[accountType] });
    } else {
        res.status(400).json({ success: false, message: "Invalid account type" });
    }
});

// 3. AI Status Endpoint
app.get('/api/ai-status', (req, res) => {
    let mockRSI = Math.floor(Math.random() * 40) + 30;
    let trend = mockRSI > 50 ? "Bullish" : "Bearish";
    let suggestion = mockRSI > 60 ? "BUY" : mockRSI < 40 ? "SELL" : "NEUTRAL";
    
    res.json({
        success: true,
        rsi: mockRSI,
        trend: trend,
        volatility: "Medium",
        suggestion: suggestion,
        lastUpdated: new Date().toLocaleTimeString()
    });
});

// 4. Live Signals Endpoint
app.get('/api/live-signal', (req, res) => {
    let mockPrice = 1.0850 + (Math.random() - 0.5) * 0.005;
    let rsi = Math.floor(Math.random() * 40) + 30;
    let signal = rsi > 60 ? "BUY" : rsi < 40 ? "SELL" : "NEUTRAL";
    
    res.json({
        success: true,
        pair: "EUR/USD",
        direction: signal,
        entry: mockPrice.toFixed(5),
        tp: (mockPrice + 0.0020).toFixed(5),
        sl: (mockPrice - 0.0010).toFixed(5),
        strength: rsi,
        status: "Active"
    });
});

// --- AI SIGNAL GENERATOR ENGINE ---
let priceHistory = [];

function generateAISignal() {
    let mockPrice = 1.0850 + (Math.random() - 0.5) * 0.005;
    priceHistory.push(mockPrice);

    if (priceHistory.length > 20) priceHistory.shift();

    if (priceHistory.length >= 10) {
        let shortSMA = priceHistory.slice(-5).reduce((a, b) => a + b, 0) / 5;
        let longSMA = priceHistory.slice(-10).reduce((a, b) => a + b, 0) / 10;

        let signal = null;
        if (shortSMA > longSMA && (shortSMA - longSMA) > 0.0002) signal = "BUY";
        else if (shortSMA < longSMA && (longSMA - shortSMA) > 0.0002) signal = "SELL";

        if (signal) {
            let entryPrice = mockPrice.toFixed(5);
            let tp = signal === "BUY" ? (mockPrice + 0.0020).toFixed(5) : (mockPrice - 0.0020).toFixed(5);
            let sl = signal === "BUY" ? (mockPrice - 0.0010).toFixed(5) : (mockPrice + 0.0010).toFixed(5);
            
            let msg = `🚨 <b>AI SIGNAL DETECTED</b> 🚨\n\n` +
                      `Pair: <b>EUR/USD</b>\n` +
                      `Direction: <b>${signal}</b>\n` +
                      `Entry: ${entryPrice}\n` +
                      `Take Profit: ${tp}\n` +
                      `Stop Loss: ${sl}\n\n` +
                      `<i>Generated by Pocket AI Engine</i>`;
            
            console.log(`AI generated a ${signal} signal! Sending to Telegram...`);
            sendTelegramMessage(msg);
            priceHistory = []; 
        }
    }
}

setInterval(generateAISignal, 30000);

app.listen(PORT, () => {
    console.log(`Backend Server running on port ${PORT}`);
    console.log(`AI Signal Engine is active and scanning the market...`);
});
